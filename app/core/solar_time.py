def get_longitude(place: str | None) -> float | None:
    """按地名查内置经度表（东经度数）。查不到返回 None。"""
    if not place:
        return None
    # 先整名匹配，再前 2 字匹配城市，最后匹配省份
    for key, lon in CITY_LONGITUDE.items():
        if key in place:
            return lon
    for key, lon in PROVINCE_LONGITUDE.items():
        if key in place:
            return lon
    return None


def equation_of_time(dt: datetime) -> float:
    """均时差（分钟）。"""
    day_of_year = dt.timetuple().tm_yday
    b = (360.0 / 365.0) * (day_of_year - 81)
    b_rad = math.radians(b)
    return 9.87 * math.sin(2 * b_rad) - 7.53 * math.cos(b_rad) - 1.5 * math.sin(b_rad)


def longitude_offset(longitude: float) -> float:
    """经度时差（分钟）。中国基准经度 120°E。"""
    return (longitude - 120.0) * 4.0


def to_true_solar_time(dt: datetime, longitude: float) -> datetime:
    """标准时间 → 真太阳时。"""
    correction = equation_of_time(dt) + longitude_offset(longitude)
    return dt + timedelta(minutes=correction)


def corrected_birth(dt: datetime, longitude: float | None) -> datetime:
    """返回校正后的出生时间；longitude 为空则原样返回。"""
    if longitude is None:
        return dt
    return to_true_solar_time(dt, longitude)
